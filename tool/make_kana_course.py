def kana_set_of(text):
    return {ch for ch in text if 'ぁ' <= ch <= 'ゟ' or ch == 'ー'}


class Builder:
    def __init__(self):
        self.lessons = []
        self.known = set()
        self.clips = {}  # text -> file
        self.nchar = 0
        self.nword = 0

    def clip(self, text, prefix):
        t = re.sub(r'[。、？！\s]+$', '', text)
        key = text
        if key not in self.clips:
            if prefix == 'c':
                self.nchar += 1
                n = self.nchar
            else:
                self.nword += 1
                n = self.nword
            self.clips[key] = 'kana_%s_%03d.mp3' % (prefix, n)
        return 'assets/audio/' + self.clips[key]

    def item(self, jp, rom, ar, emoji):
        return {'jp': jp, 'romaji': rom, 'ar': ar, 'emoji': emoji, 'audio': self.clip(jp, 'w')}

    def word(self, jp, rom, ar, emoji):
        return {'jp': jp, 'romaji': rom, 'ar': ar, 'emoji': emoji, 'audio': self.clip(jp, 'w')}

    def char(self, ch, rom, strokes, tip, sound_note, wd, audio_text=None):
        return {
            'char': ch, 'romaji': rom, 'sound_ar': sound_ar(rom),
            'note_ar': sound_note or '', 'strokes': strokes, 'tip_ar': tip,
            'audio': self.clip(audio_text or ch, 'c'), 'word': self.word(*wd),
        }

    def add(self, kind, stage, title, subtitle, chars=None, items=None, pages=None, note=None):
        self.lessons.append({
            'id': len(self.lessons) + 1, 'stage': stage, 'kind': kind, 'title_ar': title, 'subtitle_ar': subtitle,
            'note_ar': note or '', 'chars': chars or [], 'items': items or [], 'pages': pages or [],
        })

    def check_items(self, title, raw_items):
        for jp, *_ in raw_items:
            bad = kana_set_of(jp) - self.known - set('ゃゅょっー')
            bad |= {c for c in jp if not (c in '。、？！ ' or 'ぁ' <= c <= 'ゟ' or c == 'ー')}
            if bad:
                sys.exit('%s: "%s" uses kana not learned yet: %s' % (title, jp, ''.join(sorted(bad))))

    def study(self, kind, stage, title, subtitle, raw, note=None):
        self.check_items(title, raw)
        self.add(kind, stage, title, subtitle, items=[self.item(*r) for r in raw], note=note)


