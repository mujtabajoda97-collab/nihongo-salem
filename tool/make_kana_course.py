CONS = {'': '', 'k': 'ك', 's': 'س', 't': 'ت', 'n': 'ن', 'h': 'ه', 'm': 'م', 'y': 'ي', 'r': 'ر',
        'w': 'و', 'g': 'گ', 'z': 'ز', 'd': 'د', 'b': 'ب', 'p': 'پ'}
