COMBO = {'ky': 'كي', 'sh': 'ش', 'ch': 'تش', 'j': 'ج', 'hy': 'هي', 'ry': 'ري', 'by': 'بي', 'gy': 'گي'}
LONG = {'ā': 'آ (ممدودة)', 'ii': 'إيي (ممدودة)', 'ee': 'إيي (ممدودة)', 'ō': 'أُو (ممدودة)'}


def sound_ar(romaji):
    if romaji in SPECIAL:
        return SPECIAL[romaji]
    if romaji in LONG:
        return LONG[romaji]
    if romaji == 'tsu':
        return SPECIAL['tsu']
    c, v = romaji[:-1], romaji[-1]
    if c in COMBO:
        return COMBO[c] + VOW[v]
    return CONS[c] + VOW[v]


